// Converts a pixel-art SVG (built from <rect> elements) into a compact
// palette + row-string matrix consumed by the ASCII avatar renderer.
// Usage: node scripts/avatar-to-matrix.mjs [input.svg] [output.ts]
import { readFileSync, writeFileSync } from 'node:fs';

const input = process.argv[2] ?? 'src/assets/avatar.svg';
const output = process.argv[3] ?? 'src/data/avatar.ts';
const svg = readFileSync(input, 'utf8');

const viewBox = svg.match(/viewBox="([\d.\s]+)"/)?.[1].trim().split(/\s+/).map(Number);
if (!viewBox) throw new Error('SVG needs a viewBox');
const [, , width, height] = viewBox;

const rects = [...svg.matchAll(/<rect\b([^>]*)\/?>/g)].map(([, attrs]) => {
  const get = (name, fallback) => {
    const m = attrs.match(new RegExp(`\\b${name}="([^"]*)"`));
    return m ? m[1] : fallback;
  };
  return {
    x: Number(get('x', 0)),
    y: Number(get('y', 0)),
    w: Number(get('width', 0)),
    h: Number(get('height', 0)),
    fill: get('fill', '#000000').toLowerCase(),
  };
});

// The first rect covering the whole canvas is treated as background.
const bg = rects.find((r) => r.x === 0 && r.y === 0 && r.w === width && r.h === height);
const grid = Array.from({ length: height }, () => Array(width).fill(null));
for (const r of rects) {
  if (r === bg) continue;
  for (let y = r.y; y < r.y + r.h; y++) {
    for (let x = r.x; x < r.x + r.w; x++) {
      if (y >= 0 && y < height && x >= 0 && x < width) grid[y][x] = r.fill;
    }
  }
}

const palette = [];
const rows = grid.map((row) =>
  row
    .map((c) => {
      if (!c) return '.';
      let i = palette.indexOf(c);
      if (i === -1) i = palette.push(c) - 1;
      return i.toString(36);
    })
    .join(''),
);

const out = `// Generated by scripts/avatar-to-matrix.mjs — do not edit by hand.
// Each row char is a base-36 index into \`palette\`; "." is transparent.
export const avatar = {
  width: ${width},
  height: ${height},
  background: ${JSON.stringify(bg?.fill ?? null)},
  palette: ${JSON.stringify(palette)},
  rows: [
${rows.map((r) => `    '${r}',`).join('\n')}
  ],
} as const;

export type AvatarMatrix = typeof avatar;
`;
writeFileSync(output, out);
console.log(`Wrote ${output}: ${width}x${height}, ${palette.length} colors`);
